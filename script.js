function applyTheme(theme) {
  const normalizedTheme = theme === "night" ? "night" : "day";
  document.documentElement.dataset.theme = normalizedTheme;
  document.querySelectorAll('[data-theme-source="night"]').forEach((source) => {
    source.media = normalizedTheme === "night" ? "all" : "(max-width: 0px)";
  });

  if (!themeToggle || !themeIcon) {
    return;
  }

  const isNight = normalizedTheme === "night";
  themeToggle.setAttribute(
    "aria-label",
    isNight ? "Switch to day mode" : "Switch to night mode"
  );
  themeIcon.className = isNight ? "fas fa-sun" : "fas fa-moon";
}

function setupThemeToggle() {
  if (!themeToggle) {
    return;
  }

  applyTheme(document.documentElement.dataset.theme);

  themeToggle.addEventListener("click", () => {
    const nextTheme = document.documentElement.dataset.theme === "night" ? "day" : "night";
    applyTheme(nextTheme);

    try {
      localStorage.setItem(themeStorageKey, nextTheme);
    } catch {
      // Theme persistence is optional; interaction should still work.
    }
  });
}

function parseTimecode(timecode) {
  const parts = timecode.split(":");

  if (parts.length !== 2) {
    return 0;
  }

  const minutes = Number(parts[0]);
  const seconds = Number(parts[1]);
  return minutes * 60 + seconds;
}

function parseSpan(span) {
  const [beginTime, endTime] = span.split(" - ");
  const beginSeconds = parseTimecode(beginTime);
  const endSeconds = parseTimecode(endTime);
  const duration = Math.max(endSeconds - beginSeconds, 0.1);

  return { beginTime, endTime, beginSeconds, endSeconds, duration };
}

function getFileName(path) {
  return path.split("/").pop();
}

function formatClockTime(seconds) {
  const totalSeconds = Number(seconds) || 0;
  const minutes = Math.floor(totalSeconds / 60);
  const remainingSeconds = totalSeconds - minutes * 60;
  return `${String(minutes).padStart(2, "0")}:${remainingSeconds
    .toFixed(3)
    .padStart(6, "0")}`;
}

function getGlobalCaption(videoMetadata) {
  return videoMetadata?.global_prompt?.middle_caption || "";
}

function createAttributeMap(eventMetadata = {}) {
  return Object.fromEntries(
    semanticAttributeFields.map((field) => [field.name, Boolean(eventMetadata[field.key])])
  );
}

function formatScore(value) {
  return Number.isFinite(Number(value)) ? Number(value).toFixed(2) : "N/A";
}

function createQualityScores(eventMetadata = {}) {
  const scores = eventMetadata.vbench_scores || {};
  return qualityScoreFields.map((field) => ({
    name: field.name,
    value: formatScore(scores[field.key])
  }));
}

function getCameraMotionLabel(eventMetadata = {}) {
  const label = String(eventMetadata.camera_motion_label || "").trim();
  return label || (eventMetadata.has_camera_motion ? "Not specified" : "static");
}

function getCameraMotionDescription(eventMetadata = {}) {
  if (eventMetadata.camera_motion_desc) {
    return eventMetadata.camera_motion_desc;
  }

  return eventMetadata.has_camera_motion
    ? "Camera motion is annotated for this event; detailed description is unavailable."
    : "No camera motion is annotated for this event.";
}

function createEventMetadata(sequence, videoMetadata) {
  const metadataByFilename = new Map(
    (videoMetadata.events || []).map((event) => [event.filename, event])
  );
  return sequence.items.map((item, index) => {
    const eventMetadata = metadataByFilename.get(getFileName(item.video)) || videoMetadata.events[index];
    const span = eventMetadata
      ? {
          beginTime: formatClockTime(eventMetadata.start_time),
          endTime: formatClockTime(eventMetadata.end_time),
          beginSeconds: Number(eventMetadata.start_time) || 0,
          endSeconds: Number(eventMetadata.end_time) || 0,
          duration: Math.max(Number(eventMetadata.duration) || 0, 0.1)
        }
      : parseSpan(item.span);
    return {
      ...item,
      eventNumber: index + 1,
      beginTime: span.beginTime,
      endTime: span.endTime,
      beginSeconds: span.beginSeconds,
      endSeconds: span.endSeconds,
      duration: span.duration,
      caption: eventMetadata?.caption || "",
      cameraMotion: getCameraMotionLabel(eventMetadata),
      cameraMotionDescription: getCameraMotionDescription(eventMetadata),
      attributes: createAttributeMap(eventMetadata),
      qualityScores: createQualityScores(eventMetadata)
    };
  });
}


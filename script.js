function getActiveEventIndex(events, currentTime) {
  // Native video looping resets currentTime. Keep a rounded final frame on
  // the final event even when media duration slightly exceeds the annotations.
  const activeIndex = events.findIndex((event) => currentTime < event.endSeconds);
  return activeIndex === -1 ? events.length - 1 : activeIndex;
}

function updateShowcaseRow(row, sequence, eventIndex, force = false) {
  if (!force && row.dataset.activeEventIndex === String(eventIndex)) {
    return;
  }

  const event = sequence.events[eventIndex];
  const panel = row.querySelector("[data-showcase-panel]");
  const pill = row.querySelector("[data-showcase-event-pill]");

  row.dataset.activeEventIndex = String(eventIndex);
  panel.innerHTML = renderMetadataPanel(sequence, event);
  panel.classList.remove("is-switching");
  void panel.offsetWidth;
  panel.classList.add("is-switching");

  pill.textContent = `Event ${String(event.eventNumber).padStart(2, "0")} / ${String(
    sequence.events.length
  ).padStart(2, "0")}`;

  row.querySelectorAll("[data-event-index]").forEach((button) => {
    button.classList.toggle("is-active", Number(button.dataset.eventIndex) === eventIndex);
  });
}

